function cell(ref, value, type, total) {
  if (value === null || value === undefined || value === '') return '';
  const numeric = type === 'money' || type === 'int' || type === 'number' || type === 'percent';
  if (numeric && Number.isFinite(Number(value))) {
    const style = type === 'money' ? (total ? 4 : 2) : type === 'int' ? (total ? 7 : 6) : type === 'percent' ? 8 : total ? 3 : 0;
    return `<c r="${ref}" s="${style}"><v>${Number(value)}</v></c>`;
  }
  return `<c r="${ref}" t="inlineStr" s="${total ? 3 : 0}"><is><t xml:space="preserve">${xmlEsc(value)}</t></is></c>`;
}

function sheetXml({ title, columns, rows, totals }) {
  const out = [];
  let r = 1;
  if (title) {
    for (const line of [].concat(title)) {
      out.push(`<row r="${r}"><c r="A${r}" t="inlineStr" s="${r === 1 ? 5 : 0}"><is><t xml:space="preserve">${xmlEsc(line)}</t></is></c></row>`);
      r++;
    }
    r++; // fila en blanco
  }
  const headerRow = r;
  out.push(`<row r="${r}">${columns.map((c, i) => `<c r="${colName(i)}${r}" t="inlineStr" s="1"><is><t>${xmlEsc(c.header)}</t></is></c>`).join('')}</row>`);
  r++;
  for (const row of rows) {
    // Una celda puede traer su propio formato: { v: valor, t: 'int' | 'money' | ... }
    out.push(`<row r="${r}">${columns.map((c, i) => {
      const v = row[i];
      return v && typeof v === 'object' ? cell(`${colName(i)}${r}`, v.v, v.t) : cell(`${colName(i)}${r}`, v, c.type);
    }).join('')}</row>`);
    r++;
  }
  if (totals) {
    out.push(`<row r="${r}">${columns.map((c, i) => cell(`${colName(i)}${r}`, totals[i], c.type, true) || `<c r="${colName(i)}${r}" s="3"/>`).join('')}</row>`);
  }
  const lastCol = colName(columns.length - 1);
  const cols = columns.map((c, i) => `<col min="${i + 1}" max="${i + 1}" width="${c.width || 14}" customWidth="1"/>`).join('');
  const filter = rows.length ? `<autoFilter ref="A${headerRow}:${lastCol}${headerRow + rows.length}"/>` : '';
  return `<?xml version="1.0" encoding="UTF-8" standalone="yes"?>
<worksheet xmlns="http://schemas.openxmlformats.org/spreadsheetml/2006/main" xmlns:r="http://schemas.openxmlformats.org/officeDocument/2006/relationships">
  <sheetViews><sheetView workbookViewId="0"><pane ySplit="${headerRow}" topLeftCell="A${headerRow + 1}" activePane="bottomLeft" state="frozen"/></sheetView></sheetViews>
  <cols>${cols}</cols>
  <sheetData>${out.join('')}</sheetData>
  ${filter}
</worksheet>`;
}

function buildXlsx(sheets) {
  const names = sheets.map((s) => s.name.replace(/[\\/?*[\]:]/g, '').slice(0, 31));
  const files = [
    {
      name: '[Content_Types].xml',
      data: `<?xml version="1.0" encoding="UTF-8" standalone="yes"?>
<Types xmlns="http://schemas.openxmlformats.org/package/2006/content-types">
  <Default Extension="rels" ContentType="application/vnd.openxmlformats-package.relationships+xml"/>
  <Default Extension="xml" ContentType="application/xml"/>
  <Override PartName="/xl/workbook.xml" ContentType="application/vnd.openxmlformats-officedocument.spreadsheetml.sheet.main+xml"/>
  <Override PartName="/xl/styles.xml" ContentType="application/vnd.openxmlformats-officedocument.spreadsheetml.styles+xml"/>
  ${names.map((_, i) => `<Override PartName="/xl/worksheets/sheet${i + 1}.xml" ContentType="application/vnd.openxmlformats-officedocument.spreadsheetml.worksheet+xml"/>`).join('')}
</Types>`,
    },
    {
      name: '_rels/.rels',
      data: `<?xml version="1.0" encoding="UTF-8" standalone="yes"?>
<Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships">
  <Relationship Id="rId1" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/officeDocument" Target="xl/workbook.xml"/>
</Relationships>`,
    },
    {
      name: 'xl/workbook.xml',
      data: `<?xml version="1.0" encoding="UTF-8" standalone="yes"?>
<workbook xmlns="http://schemas.openxmlformats.org/spreadsheetml/2006/main" xmlns:r="http://schemas.openxmlformats.org/officeDocument/2006/relationships">
  <sheets>${names.map((n, i) => `<sheet name="${xmlEsc(n)}" sheetId="${i + 1}" r:id="rId${i + 1}"/>`).join('')}</sheets>
</workbook>`,
    },
    {
      name: 'xl/_rels/workbook.xml.rels',
      data: `<?xml version="1.0" encoding="UTF-8" standalone="yes"?>
<Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships">
  ${names.map((_, i) => `<Relationship Id="rId${i + 1}" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/worksheet" Target="worksheets/sheet${i + 1}.xml"/>`).join('')}
  <Relationship Id="rId${names.length + 1}" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/styles" Target="styles.xml"/>
</Relationships>`,
    },
    { name: 'xl/styles.xml', data: STYLES },
    ...sheets.map((s, i) => ({ name: `xl/worksheets/sheet${i + 1}.xml`, data: sheetXml(s) })),
  ];
  return zip(files);
}

module.exports = { buildXlsx };
